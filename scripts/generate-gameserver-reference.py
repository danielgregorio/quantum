#!/usr/bin/env python
"""Generate docs/targets/gameserver.md — a world's language, the game server's — from its schema. Never by hand.

    python scripts/generate-gameserver-reference.py          # rewrite the page
    python scripts/generate-gameserver-reference.py --check  # exit 1 when the page is stale

The tags and what they mean come from quantum/runtime/gameserver/schema.py, the table a world is read against; the
functions from quantum/runtime/gameserver/rules.py; the protocol from the server's own docstring; and the example
is the world of the tests, tests/gameserver/worlds/yard/yard.server.q, whole. So the page cannot say what the server
does not. tests/docs/test_gameserver_reference_is_generated.py fails when the committed page is not this output.
"""

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from quantum.runtime.gameserver import server as server_module  # noqa: E402
from quantum.runtime.gameserver.rules import FUNCTION_DOCS  # noqa: E402
from quantum.runtime.gameserver.schema import TAGS  # noqa: E402

OUT = REPO / 'docs' / 'targets' / 'gameserver.md'
YARD = REPO / 'tests' / 'gameserver' / 'worlds' / 'yard' / 'yard.server.q'

INTRO = '''---
title: The game server (Laboratory)
outline: [2, 3]
---

<!-- Generated by scripts/generate-gameserver-reference.py from quantum/runtime/gameserver/schema.py. Do not edit. -->

# The game server

> **Laboratory.** The game server is being built, a phase at a time, by
> [PLAN_GAME_SERVER.md](https://github.com/danielgregorio/quantum/blob/main/PLAN_GAME_SERVER.md); it carries no
> stability promise and may change in any release (`SUPPORT_TIERS.md`). This page is what is built: Phase 1, the
> world lives.

A `q:application type="gameserver"` is a game's world: its map, its entities, what each player may ask it
(`q:command`) and its rules (`q:every`, `q:on-join`). The author says those; the network, the saving and the
replay are the Quantum's. A command runs whole or not at all, as the player who sent it: a `q:require` that does
not hold, an argument it does not take, a command faster than its `limit=`, and nothing it did stays. The world is
deterministic (its random is its own, seeded), so a snapshot and the inputs after it are the world: that is how a
restart loses no command a player was told ran, and how a test is exact.

```bash
quantum gameserver check yard.server.q        # read against the schema: what is wrong, with its line
quantum gameserver run yard.server.q          # the world on ws://127.0.0.1:7700, ten ticks a second
quantum gameserver run yard.server.q --step   # a test world: it ticks only when a client says "step"
```

The world keeps a snapshot every five minutes (`--snapshot-every`) and every input in a log, in
`.quantum/gameserver/<name>/` (`--data`); a stop writes the snapshot, a kill leaves the log, and either comes back.

'''

TYPES = '''## Attribute types

| Type | What it is |
|---|---|
| `ident` | a name (`[A-Za-z_][A-Za-z0-9_-]*`) |
| `names` | names separated by commas (`dir, speed`) |
| `text` | a string; `{...}` in it is an expression, read when it runs |
| `value` | a number, `true`, `false`, `null` or a text as written; or, all in braces, an expression (`{[]}`) |
| `expr` | an expression, with or without its braces |
| `place` | an area of the map by its name, or an expression giving a tile, an entity or an area's name |
| `int`, `bool` | a whole number; `true` or `false` |
| `rate` | so many in so long: `8/s`, `1/3s`, `30/m` |
| `duration` | `500ms`, `2s`, `5m`, `1h` |
| `enum` | one of the values listed |

'''


def attr_table(attrs):
    lines = ['| Attribute | Type | Default | What it is |', '|---|---|---|---|']
    for name, attr in attrs.items():
        default = 'required' if attr.required else ('' if attr.default in (None, '') else f'`{attr.default}`')
        kind = attr.type if not attr.type.startswith('enum:') else 'enum: ' + ', '.join(
            f'`{v}`' for v in attr.type[5:].split('|'))
        lines.append(f'| `{name}=` | {kind} | {default} | {attr.doc} |')
    return '\n'.join(lines) + '\n'


def parent_text(p):
    if p == 'application':
        return '`<q:application type="gameserver">`'
    if p == 'handler':
        return 'a block (a `q:command`, `q:every`, `q:on-join`, `q:on-leave`, a `q:function`, and the `q:if`, ' \
               '`q:elseif`, `q:else` and `q:loop` in them)'
    return f'`<q:{p}>`'


def tags_section():
    out = ['## The tags\n\n']
    for name, tag in TAGS.items():
        parents = ', '.join(parent_text(p) for p in tag.parents)
        out.append(f'### `q:{name}`\n\n{tag.doc}\n\nGoes inside {parents}.\n\n')
        if tag.attrs:
            out.append(attr_table(tag.attrs) + '\n')
    return ''.join(out)


def functions_section():
    out = ['## What an expression may call\n\nThe Core\'s expressions and their stdlib (`len`, `round`, `min`, '
           '`join`...), a world\'s own `q:function`s, and:\n\n| Function | What it gives |\n|---|---|\n']
    for sig, doc in FUNCTION_DOCS.items():
        out.append(f'| `{sig}` | {doc} |\n')
    return ''.join(out) + '\n'


def protocol_section():
    doc = server_module.__doc__
    start = doc.index('    client:')
    end = doc.index('A tick frame goes')
    block = '\n'.join(line[4:] if line.startswith('    ') else line for line in doc[start:end].rstrip().splitlines())
    rest = ' '.join(doc[end:].split())
    return ('## The protocol\n\nJSON over a WebSocket, a message a frame: what a game, a page or a test speaks to '
            'a world.\n\n```\n' + block + '\n```\n\n' + rest + '\n\n'
            'In Python, `quantum.runtime.gameserver.session` speaks it with the play protocol\'s words: '
            '`serve_world(path)` runs a world in a thread (a test world by default), and `WorldSession(url, name)` '
            'is a player, with `observe()`, `act(send=[(command, args)], ticks=n)` and `until(condition)`.\n\n')


def example_section():
    source = YARD.read_text(encoding='utf-8').rstrip('\n')
    return ('## A world, whole\n\n`tests/gameserver/worlds/yard/yard.server.q`, the world of the tests: a walled '
            'yard, a hero a player gets, a step at four steps a second, coins.\n\n```xml\n' + source + '\n```\n')


def build() -> str:
    return INTRO + TYPES + tags_section() + functions_section() + protocol_section() + example_section()


def main() -> int:
    text = build()
    if '--check' in sys.argv:
        if not OUT.is_file() or OUT.read_text(encoding='utf-8') != text:
            print(f'{OUT.relative_to(REPO)} is stale: run python scripts/generate-gameserver-reference.py')
            return 1
        print(f'{OUT.relative_to(REPO)} is current')
        return 0
    OUT.write_text(text, encoding='utf-8')
    print(f'wrote {OUT.relative_to(REPO)}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
