def config_page():
    # A copy of the module, loaded from its file: the test suite redirects the
    # default paths of the imported one (no test writes into the repository).
    spec = importlib.util.spec_from_file_location('web_config_as_shipped',
                                                  REPO / 'quantum' / 'runtime' / 'web_config.py')
    web_config = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(web_config)
    defaults = web_config.ConfigLoading()._load_config(str(REPO / 'does-not-exist.yaml'))
    known = dict(web_config._KNOWN_KEYS)
    known.setdefault('datasources', set()).update(web_config._DATASOURCE_KEYS)
    typed = {}
    for (section, key), kind in web_config._TYPED.items():
        typed[(section, key)] = kind.__name__
        known.setdefault(section, set()).add(key)
    for section, key in re.findall(r'`(\w+)\.(\w+)[`:]', SPEC_TEXT):
        if section in web_config._KNOWN_SECTIONS and key.islower():
            known.setdefault(section, set()).add(key)
    body = []
    for section in sorted(web_config._KNOWN_SECTIONS):
        anchor = f'cfg-{section}'
        ids = mentions(r'(?<![\w.])`?' + re.escape(section) + r'[.:`]')
        cite(ids, f'`{section}:`', f'./config#{anchor}')
        body.append(f'<a id="{anchor}"></a>\n\n## `{section}`\n')
        if section == 'datasources':
            body.append('A map of datasource name → its keys (DB-7): `datasources: {db: {driver: sqlite, '
                        'database: ./app.db}}`.\n')
        keys = sorted(known.get(section, ()))
        if keys:
            body.append('| Key | Type | Default | Rules |\n|---|---|---|---|')
            for key in keys:
                value = (defaults.get(section) or {}).get(key) if isinstance(defaults.get(section), dict) else None
                key_ids = mentions(r'`' + re.escape(f'{section}.{key}') + r'`') + \
                    mentions(r'(?<![\w.])`' + re.escape(key) + r'`') if section in web_config._KNOWN_KEYS else \
                    mentions(r'`' + re.escape(f'{section}.{key}') + r'`')
                key_ids = sorted(set(key_ids), key=lambda r: (r.split('-')[0], int(r.split('-')[1])))
                cite(key_ids, f'`{section}.{key}`', f'./config#{anchor}')
                shown = '' if value is None or key in ('secret_key',) else f'`{value}`'
                body.append(f'| `{key}` | {typed.get((section, key), "")} | {shown} | {rule_links(key_ids)} |')
            body.append('')
        if section in web_config._KNOWN_KEYS:
            body.append('Another key in this section is warned about when the configuration is loaded '
                        '([CFG-2](./spec#CFG-2), [CFG-3](./spec#CFG-3)).\n')
        elif section != 'datasources':
            body.append('Accepted; its keys are not checked.\n')
        if ids:
            body.append('Specified by: ' + rule_links(ids) + '\n')
    intro = ('`quantum.config.yaml`, next to the app. `${NAME}` in any value is the environment variable '
             '`NAME` ([CFG-1](./spec#CFG-1)); a section not listed here is warned about.')
    return page('Configuration', intro, '\n'.join(body))

# ------------------------------------------------------------------ spec


def spec_page():
    """SPEC.md by paragraph (code spans wrap across lines): an anchor per rule, its backlinks after it."""
    blocks, block, fenced = [], [], False
    for line in SPEC_TEXT.splitlines()[1:]:           # the page has its own title
        if line.startswith('```'):
            fenced = not fenced
        if not line.strip() and not fenced:
            if block:
                blocks.append('\n'.join(block))
            block = []
        else:
            block.append(line)
    if block:
        blocks.append('\n'.join(block))
    out = []
    for text in blocks:
        if text.startswith('```'):
            out.append(text)
            continue
        m = re.match(r'\*\*([A-Z]+-\d+)\*\* ', text)
        if not m:
            out.append(prose(text, prefix=''))
            continue
        rid = m.group(1)
        out.append(f'<a id="{rid}"></a>**[{rid}](#{rid})** ' + prose(text[m.end():], prefix=''))
        out.extend(_backlinks(rid))
    body = '\n\n'.join(out)
    body = re.sub(r'\]\(((?!https?:|#|\./|\.\./)[\w./-]+\.md)\)', lambda m: f']({GITHUB}{m.group(1)})', body)
    intro = ('The specification of the Core and the AI, rule by rule: each rule has an anchor '
             '(`spec#EXPR-14`) and lists the Reference entries that cite it. Source: '
             f'[SPEC.md]({GITHUB}SPEC.md).')
    return page('Specification', intro, body)


def _backlinks(rid):
    import html
    entries = BACKLINKS.get(rid)
    if not entries:
        return []
    return ['<p class="spec-cited">Referenced by: ' +
            ' · '.join(f'<a href="{link}"><code>{html.escape(label.strip("`"))}</code></a>'
                       for label, link in entries) + '</p>']

# ------------------------------------------------------------------ index


def index_page(counts):
    body = f"""| Page | What it lists |
|---|---|
| [Tags](./tags) | The {counts['tags']} Core and AI tags: attributes, types, values, defaults, rules |
| [Expression functions](./functions) | The {counts['functions']} functions an expression can call |
| [Command line](./cli) | `quantum` and its commands, options and defaults |
| [Configuration](./config) | The sections and keys of `quantum.config.yaml` |
| [Specification](./spec) | The {counts['rules']} rules of the SPEC, each with an anchor |
| [Experimental tags](./experimental) | Tags outside the Core and the AI |
"""
    intro = ('Generated from the code and the SPEC on every change: what is here is what the parser, '
             'the runtime and the command line do. The Guide explains; this lists.')
    return page('Reference', intro, body)


def pages():
    """{file name: content} — in dependency order: SPEC backlinks come from the other pages."""
    BACKLINKS.clear()
    result = {
        'tags.md': tags_page(),
        'experimental.md': experimental_page(),
        'functions.md': functions_page(),
        'cli.md': cli_page(),
        'config.md': config_page(),
    }
    result['spec.md'] = spec_page()
    from quantum.core.expression_stdlib import STDLIB
    schema = load_lsp_schema()
    core = importlib.import_module(schema.__name__ + '.core_tags').CORE_AI_TAGS
    result['index.md'] = index_page({'tags': len(core), 'functions': len(STDLIB), 'rules': len(RULES)})
    return result


def main():
    generated = pages()
    if '--check' in sys.argv:
        stale = [name for name, text in generated.items()
                 if not (OUT / name).exists() or (OUT / name).read_text(encoding='utf-8') != text]
        if stale:
            print('not current:', ', '.join(stale), '— run python scripts/generate-reference.py')
            return 1
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in generated.items():
        (OUT / name).write_text(text, encoding='utf-8', newline='\n')
    print('wrote', len(generated), 'pages to', OUT.relative_to(REPO))
    return 0


if __name__ == '__main__':
    sys.exit(main())
