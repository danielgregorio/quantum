from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from quantum.runtime.screen.schema import ACTIONS, EVENTS, TAGS  # noqa: E402

OUT = REPO / 'docs' / 'targets' / 'screen.md'
OS_SCREEN = REPO / 'os' / 'config' / 'screen' / 'screen.q'

INTRO = '''---
title: The Hive's screen (Laboratory)
outline: [2, 3]
---

<!-- Generated by scripts/generate-screen-reference.py from quantum/runtime/screen/schema.py. Do not edit. -->

# The Hive's screen

> **Laboratory.** The screen language exists to press on the language and
> to drive Quantum OS; it carries no stability promise and may change in
> any release (`SUPPORT_TIERS.md`).

A `q:application type="screen"` is what the Hive of Quantum OS shows on the
machine's screen: a small pixel-art scene and, per event of the Hive, what
happens in it. It compiles to `screen.toml`, a font sheet and the sprite
sheets, which `hive-screen` (`os/crates/hive-screen`) loads: a daemon of a
few hundred kilobytes that draws the scene on the console, lists the
Hive's offers for an administrator to approve with the keyboard, and
sends the approval back through the same socket the dashboard uses. No
engine, no compositor, no GPU: the scene is drawn on the CPU and scaled
up by a whole number to fill the display.

```bash
quantum run screen.q --out projects/screen/screen   # writes screen.toml, font.png and the sheets
python scripts/generate-screen-config.py            # the OS's own: os/config/screen/screen.q -> os/config/screen/
```

The vocabulary of the scene is the games' (`qg:`): a sheet of frames, an
animation, a tween with the same curves, the same particle presets, with
the same meaning. What moves the scene are the Hive's events, the same
ones [the rules](/targets/hive) are on, with the same `{field}`s, filled
in from the event itself. There is nothing to compute: no statements, no
expressions, and text where a tag goes is a compile error.

## The shape of a screen

```xml
<q:application id="screen" type="screen">
  <qs:sheet name="cell" src="art/cells.png" tile="24">
    <qs:animation name="smoke" frames="2,3,4,5,6,2" fps="4" loop="false" />
  </qs:sheet>
  <qs:particles name="stars" preset="stars" />

  <qs:scene width="320" height="180" background="#1a1a2e">
    <qs:text value="Quantum OS" x="6" y="4" color="#ffd34d" />
    <qs:sprite name="nginx" sheet="cell" frame="1" x="6" y="22" />
    <qs:text value="nginx" x="34" y="29" />
    <qs:offers x="186" y="34" width="130" rows="8" />
    <qs:notices x="6" y="142" width="308" rows="2" />
  </qs:scene>

  <qs:on event="service-crash">
    <qs:animate target="{service}" name="smoke" />     <!-- the sprite named after the service -->
    <qs:say text="{service} stopped (exit {exit_code})" />
  </qs:on>
  <qs:on event="done">
    <qs:frame target="{service}" frame="0" />
    <qs:emit particles="stars" at="{service}" dx="12" dy="12" />
  </qs:on>
</q:application>
```

A sprite's name is how a rule reaches it: `{service}` on `service-crash`
is `nginx`, and the sprite named `nginx` smokes. An action whose target no
sprite is named, or whose `{field}` the event does not provide, is left
out, as the rules leave out an offer they cannot fill in. The rule on
`service-crash` compiles to this, in `screen.toml`:

```toml
[[rules]]
event = "service-crash"

[[rules.actions]]
kind = "animate"
target = "{service}"
name = "smoke"

[[rules.actions]]
kind = "say"
text = "{service} stopped (exit {exit_code})"
seconds = 4.0
```

## The font

Every screen gets the same face: a 5x7 pixel font of our own, in 6x10
cells, with the printable ASCII characters and the Latin-1 letters (the
accents of Portuguese, Spanish, French, German composed from the base
letters). It is written as `font.png` next to the scene, so to the daemon
it is one more sheet. A character the font lacks shows as a box.

'''

TYPES = '''## Attribute types

| Type | What it is |
|---|---|
| `text` | a string; in a rule, `{field}` placeholders allowed |
| `ident` | a name (letters, digits, `_ @ . : -`) |
| `int` | a whole number |
| `float` | a number |
| `bool` | `true` or `false` |
| `color` | `#rgb` or `#rrggbb` |
| `tile` | a frame size in pixels: `24`, or `16x24` |
| `frames` | frame numbers separated by commas |
| `src` | a PNG next to the .q, or in a folder below it |
| `enum` | one of the values listed |

'''

AFTER = '''## What is refused

A compile error names the line. The compiler refuses:

- a tag, an attribute, an event or an action the schema does not list;
- a sheet that is not there, is not a PNG, or is not a whole number of its frames; a frame a sheet
  does not have; an animation its sheet lacks; a sprite of a sheet that does not exist;
- a `{field}` that is not a field of the rule's event; a `{field}` in the scene (it is filled in from
  an event, so it goes in a `qs:on`);
- a literal target no sprite is named; an animation the target's sheet lacks; particles no
  `qs:particles` declares;
- a `q:` statement, an expression, or text where a tag goes;
- two `qs:on` on one event, a `qs:on` with nothing to do, two `qs:scene`, two `qs:offers`, two sprites
  of one name, a tween of no time.

`hive-screen` refuses a `screen.toml` that is not what the compiler writes,
whole; it never guesses at a scene.

## How it reaches the daemon

`screen.toml`, `font.png` and the sheets are installed under
`/etc/hive/screen/`. The OS's own are written from `os/config/screen/screen.q`
by `scripts/generate-screen-config.py` (the art by `scripts/art/hive_screen.py`),
committed as written and checked in CI. `hive-screen` connects to
`hive-cortex`'s user socket as the dashboard does, and cortex lets it in as
one: it receives every notice with the event's name and fields, and every
offer, and may approve and dismiss. The Hive lab (`os/crates/hive-lab`)
runs the real `hive-screen` with no display and reads what it shows as
data (`{"op":"screen","play":{"op":"until","offer":"Restart nginx"}}`); a
test of the daemon compares its frames pixel for pixel with references.

## The levels

How much the daemon shows is a presentation level, chosen as it runs by the
frame time it measures, never above what the machine's cores allow (read as
it runs: a vCPU plugged in counts within half a second):

| Level | Needs | Shows |
|---|---|---|
| 0 `plain` | 1 core | the scene as declared, no particles, at most 15 pictures a second |
| 1 `effects` | 2 cores | the particles too (`qs:emit`, and every `qs:emitter` of `level="1"`), at most 30 a second |
| 2 `fine` | 4 cores | two pixels to the scene's one: a tween or a particle lands on its own pixel, the font's pixels are blocks; and the emitters of `level="2"` |

A level changes how the scene shows, never what happens in it: the same
ticks run at every level, and a rule's actions run the same. The frame is
drawn in bands, one thread a core, and is the same picture whatever their
number. A scene at rest costs nothing at any level. The lab, the tests and
`--play` play at level 1 unless asked (`{"op":"level","level":2}`).

'''


def attr_table(attrs):
    lines = ['| Attribute | Type | Default | What it is |', '|---|---|---|---|']
    for name, attr in attrs.items():
        default = 'required' if attr.required else ('' if attr.default is None else f'`{attr.default}`')
        kind = attr.type if not attr.type.startswith('enum:') else 'enum: ' + ', '.join(
            f'`{v}`' for v in attr.type[5:].split('|'))
        lines.append(f'| `{name}=` | {kind} | {default} | {attr.doc} |')
    return '\n'.join(lines) + '\n'


def tags_section():
    out = ['## The tags\n\n']
    for name, tag in TAGS.items():
        parents = ', '.join('`<q:application>`' if p == 'application' else f'`<qs:{p}>`' for p in tag.parents)
        out.append(f'### `qs:{name}`\n\n{tag.doc}\n\nGoes inside {parents}.\n\n')
        if tag.attrs:
            out.append(attr_table(tag.attrs) + '\n')
    return ''.join(out)


def events_section():
    out = ['## The events\n\nWhat a `qs:on` can be on. The observations are the ones [the rules](/targets/hive) '
           'name, as `hive-cortex` tells them to its clients, each with `title`, `body` and `severity` besides its '
           'own fields; the rest are the screen\'s own.\n\n']
    for name, event in EVENTS.items():
        out.append(f'### `{name}`\n\n{event.doc}\n\n| Field | Type | What it is |\n|---|---|---|\n')
        for fname, f in event.fields.items():
            out.append(f'| `{{{fname}}}` | {f.type} | {f.doc} |\n')
        out.append('\n')
    return ''.join(out)


def actions_section():
    return ('## The actions\n\nWhat a `qs:on` holds, in order: ' +
            ', '.join(f'[`qs:{a}`](#qs-{a})' for a in ACTIONS) +
            '. A target is a sprite\'s name or a `{field}` that is one.\n\n')


def os_section():
    source = OS_SCREEN.read_text(encoding='utf-8').rstrip('\n')
    return ('## The screen Quantum OS ships\n\n`os/config/screen/screen.q`, whole: a honeycomb with a cell per '
            'service the whitelist names, a bee, the offers and the notices.\n\n```xml\n' + source + '\n```\n')


def build() -> str:
    return INTRO + TYPES + tags_section() + events_section() + actions_section() + AFTER + os_section()


def main() -> int:
    text = build()
    if '--check' in sys.argv:
        if not OUT.is_file() or OUT.read_text(encoding='utf-8') != text:
            print(f'{OUT.relative_to(REPO)} is stale: run python scripts/generate-screen-reference.py')
            return 1
        print(f'{OUT.relative_to(REPO)} is current')
        return 0
    OUT.write_text(text, encoding='utf-8')
    print(f'wrote {OUT.relative_to(REPO)}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
