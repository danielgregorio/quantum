#!/usr/bin/env python
"""Generate docs/targets/hive.md — the Hive's rule language — from the schema. Never by hand.

    python scripts/generate-hive-reference.py          # rewrite the page
    python scripts/generate-hive-reference.py --check  # exit 1 when the page is stale

The tags, events and actions and what they mean come from
quantum/runtime/hive/schema.py: the table the compiler validates against,
so the page cannot say what the compiler does not. The rules Quantum OS
ships (os/config/hive/hive.q) are included whole: they are the example, and
every block on the page compiles in CI (tests/hive/test_hive_docs.py).

tests/docs/test_hive_reference_is_generated.py fails when the committed
page is not this script's output.
"""

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from quantum.runtime.hive.schema import ACTIONS, EVENTS, LIMITS, PERMITS, TAGS  # noqa: E402

OUT = REPO / 'docs' / 'targets' / 'hive.md'
OS_RULES = REPO / 'os' / 'config' / 'hive' / 'hive.q'

INTRO = '''---
title: The Hive's rules (Laboratory)
outline: [2, 3]
---

<!-- Generated by scripts/generate-hive-reference.py from quantum/runtime/hive/schema.py. Do not edit. -->

# The Hive's rules

> **Laboratory.** The Hive's rule language exists to press on the language
> and to drive Quantum OS; it carries no stability promise and may change in
> any release (`SUPPORT_TIERS.md`).

A `q:application type="hive"` is the rules of the Hive, the set of daemons
that watch a Quantum OS system (`os/` in the repository): what the Hive
offers when something happens, and what its actuator may do at all, in
tags. It compiles to two files the daemons load: `rules.toml`, which
`hive-synapse` reads to turn an event into offers an administrator may
approve, and `whitelist.toml`, which `hive-actuator` checks every action
against before running it. There is nothing to compute in a hive: no
statements, no expressions, and text where a tag goes is a compile error.

```bash
quantum run hive.q --out projects/hive/hive   # writes rules.toml and whitelist.toml
python scripts/generate-hive-config.py        # the OS's own: os/config/hive/hive.q -> os/config/hive/
```

Two things are checked before anything runs. A `{field}` in an offer is a
field the event has, of the right type, and it is filled in by
`hive-synapse` from the event itself, never from the model's text. And an
offer the file's own whitelist would refuse does not compile, so an
administrator never approves something that fails.

## The shape of a hive

```xml
<q:application id="hive" type="hive">
  <qh:on event="service-crash">
    <qh:offer title="Restart {service}"
              description="{unit} stopped unexpectedly. Run `systemctl restart {service}`."
              action="restart-service" service="{service}" />
    <qh:offer title="Show recent logs for {service}"
              action="run-command" cmd="journalctl" args="-n 50 -u {service}" />
  </qh:on>
  <qh:on event="command-not-found">
    <qh:offer title="Install {package}" action="install-package" package="{package}" />
  </qh:on>

  <qh:allow command="journalctl" args="-n 50 -u *" />   <!-- `*`: any one argument -->
  <qh:allow service="nginx postgresql redis-server" />
  <qh:block service="hive-* systemd-* dbus sshd" />      <!-- a block wins over an allow -->
  <qh:block package="systemd libc6 apt dpkg" />          <!-- never removed -->
  <qh:limit action="install-package" per-minute="5" />
</q:application>
```

The rule on `service-crash` compiles to this, in `rules.toml`, with every
parameter a string that `hive-synapse` types once the fields are filled in:

```toml
[[rules]]
event = "service-crash"

[[rules.offers]]
title = "Restart {service}"
description = "{unit} stopped unexpectedly. Run `systemctl restart {service}`."
action = "restart-service"
service = "{service}"
```

'''

TYPES = '''## Attribute types

| Type | What it is |
|---|---|
| `text` | a string; `{field}` placeholders allowed |
| `args` | words separated by spaces, each a placeholder or not |
| `int` | a number, or a `{field}` of a field that is one |
| `bool` | `true` or `false` |
| `words` | one or more names separated by spaces |
| `enum` | one of the values listed |

'''

AFTER = '''## What is refused

A compile error names the line. The compiler refuses:

- a tag, an attribute, an event or an action the schema does not list;
- a `{field}` that is not a field of the rule's event, or a text field where a number goes;
- an offer the file's own whitelist would refuse: a command no `qh:allow command=` permits
  (an argument that is a `{field}` needs a `*` in its place), a service no allow permits or a
  block names, a package a block names, a dataset no allow permits, or a permission the file
  does not switch on;
- a `q:` statement, an expression, or text where a tag goes;
- two `qh:on` on one event, a `qh:on` with nothing to offer, a `qh:allow` of two things at once,
  a `qh:limit` given twice or of less than one a minute.

What the compiler cannot check, the daemons do. `hive-synapse` refuses a
`rules.toml` that fails the same checks and uses the rules its build was made
with; an offer whose value is not what its action takes at run time (a port
that is not a number, a unit that is not a service) is left out, never
guessed. `hive-actuator` checks every action against the whitelist, which
fails closed, and rebooting, shutting down and suspending have no switch at
all.

## How it reaches the daemons

`rules.toml` and `whitelist.toml` are installed as `/etc/hive/rules.toml`
and `/etc/hive/whitelist.toml`. The OS's own files are written from
`os/config/hive/hive.q` by `scripts/generate-hive-config.py`, committed as
written and checked in CI, and `hive-synapse` embeds the committed
`rules.toml` as its built-in rules, for a system without the file. The Hive
lab (`os/crates/hive-lab`) plays a tape per rule against the real
`hive-cortex` and `hive-synapse` in a fraction of a second; the VM lab
(`os/scripts/lab/vm`) follows the same rules through the real system.

'''


def attr_table(attrs):
    lines = ['| Attribute | Type | Default | What it is |', '|---|---|---|---|']
    for name, attr in attrs.items():
        default = 'required' if attr.required else ('' if attr.default is None else f'`{attr.default}`')
        kind = attr.type if not attr.type.startswith('enum:') else 'enum: ' + ', '.join(
            f'`{v}`' for v in attr.type[5:].split('|'))
        lines.append(f'| `{name}=` | {kind} | {default} | {attr.doc} |')
    return '\n'.join(lines) + '\n'


def tags_section():
    out = ['## The tags\n\n']
    for name, tag in TAGS.items():
        parents = ', '.join('`<q:application>`' if p == 'application' else f'`<qh:{p}>`' for p in tag.parents)
        out.append(f'### `qh:{name}`\n\n{tag.doc}\n\nGoes inside {parents}.\n\n')
        if tag.attrs:
            out.append(attr_table(tag.attrs) + '\n')
        if name == 'offer':
            out.append('Plus the attributes of its `action=`, listed under [the actions](#the-actions).\n\n')
    return ''.join(out)


def events_section():
    out = ['## The events\n\nWhat a `qh:on` can be on: the observations `hive-cortex` passes to `hive-synapse` '
           '(`HiveMessage` in `os/crates/hive-common/src/messages.rs`), and the fields an offer may hold as '
           '`{field}`.\n\n']
    for name, event in EVENTS.items():
        out.append(f'### `{name}`\n\n{event.doc} (`{event.message}`)\n\n| Field | Type | What it is |\n|---|---|---|\n')
        for fname, f in event.fields.items():
            out.append(f'| `{{{fname}}}` | {f.type} | {f.doc} |\n')
        out.append('\n')
    return ''.join(out)


def actions_section():
    out = ['## The actions\n\nWhat a `qh:offer` can name: the `Action` variants `hive-actuator` runs '
           '(`os/crates/hive-common/src/actions.rs`), each under the kebab-case of its name, with the '
           'attributes it takes.\n\n']
    for name, spec in ACTIONS.items():
        out.append(f'### `{name}`\n\n{spec.doc} (`Action::{spec.variant}`)\n\n')
        if spec.params:
            out.append(attr_table(spec.params) + '\n')
        else:
            out.append('Takes no attribute.\n\n')
    out.append('### What `qh:limit` may name\n\nEvery `Action` variant, in kebab-case: ' +
               ', '.join(f'`{k}`' for k in LIMITS) + '.\n\n')
    out.append('### What `qh:allow action=` may switch on\n\n' +
               ', '.join(f'`{p}`' for p in PERMITS) + '. Off unless the file switches it on.\n\n')
    return ''.join(out)


def os_section():
    source = OS_RULES.read_text(encoding='utf-8').rstrip('\n')
    return ('## The rules Quantum OS ships\n\n`os/config/hive/hive.q`, whole: the five rules and the whitelist '
            'the daemons run with.\n\n```xml\n' + source + '\n```\n')


def build() -> str:
    return INTRO + TYPES + tags_section() + events_section() + actions_section() + AFTER + os_section()


def main() -> int:
    text = build()
    if '--check' in sys.argv:
        if not OUT.is_file() or OUT.read_text(encoding='utf-8') != text:
            print(f'{OUT.relative_to(REPO)} is stale: run python scripts/generate-hive-reference.py')
            return 1
        print(f'{OUT.relative_to(REPO)} is current')
        return 0
    OUT.write_text(text, encoding='utf-8')
    print(f'wrote {OUT.relative_to(REPO)}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
