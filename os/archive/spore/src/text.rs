#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_font_creation() {
        let font = BitmapFont::default_8x8();
        assert_eq!(font.char_width, 8);
        assert_eq!(font.char_height, 8);
    }

    #[test]
    fn test_text_measurement() {
        let font = BitmapFont::default_8x8();
        assert_eq!(font.measure_string("Hello"), 40);
    }

    #[test]
    fn test_text_renderer() {
        let mut canvas = Canvas::new(100, 100);
        let renderer = TextRenderer::default_font();
        renderer.draw(&mut canvas, 10, 10, "Hi", Color::WHITE);
        // Should have drawn some non-black pixels
        let has_white = canvas.pixels().iter().any(|&p| p != Color::BLACK.to_argb());
        assert!(has_white);
    }
}
