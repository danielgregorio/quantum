//! Text rendering with bitmap fonts
//!
//! Provides a simple bitmap font system for rendering text to a Canvas.

use crate::canvas::Canvas;
use crate::color::Color;

/// A simple bitmap font (8x8 or 8x16 characters)
pub struct BitmapFont {
    /// Character width
    pub char_width: u32,
    /// Character height
    pub char_height: u32,
    /// Glyph data (1 bit per pixel, row-major)
    glyphs: Vec<Vec<u8>>,
    /// First character code
    first_char: u8,
}

impl BitmapFont {
    /// Create a new bitmap font
    pub fn new(char_width: u32, char_height: u32, first_char: u8) -> Self {
        Self {
            char_width,
            char_height,
            glyphs: Vec::new(),
            first_char,
        }
    }

    /// Create the built-in 8x8 font
    pub fn default_8x8() -> Self {
        let mut font = Self::new(8, 8, 32);
        font.glyphs = FONT_8X8.iter().map(|g| g.to_vec()).collect();
        font
    }

    /// Add a glyph to the font
    pub fn add_glyph(&mut self, data: Vec<u8>) {
        self.glyphs.push(data);
    }

    /// Get glyph data for a character
    fn get_glyph(&self, c: char) -> Option<&[u8]> {
        let code = c as u8;
        if code >= self.first_char {
            let idx = (code - self.first_char) as usize;
            self.glyphs.get(idx).map(|g| g.as_slice())
        } else {
            None
        }
    }

    /// Draw a single character
    pub fn draw_char(&self, canvas: &mut Canvas, x: i32, y: i32, c: char, color: Color) {
        if let Some(glyph) = self.get_glyph(c) {
            for row in 0..self.char_height as usize {
                if row >= glyph.len() {
                    break;
                }
                let bits = glyph[row];
                for col in 0..self.char_width as usize {
                    if (bits >> (7 - col)) & 1 != 0 {
                        canvas.set_pixel(x + col as i32, y + row as i32, color);
                    }
                }
            }
        }
    }

    /// Measure the width of a string
    pub fn measure_string(&self, s: &str) -> u32 {
        s.chars().count() as u32 * self.char_width
    }

    /// Measure the height of a string (accounts for newlines)
    pub fn measure_string_height(&self, s: &str) -> u32 {
        let lines = s.lines().count().max(1);
        lines as u32 * self.char_height
    }
}

/// High-level text renderer
pub struct TextRenderer {
    font: BitmapFont,
}

impl TextRenderer {
    /// Create a new text renderer with the given font
    pub fn new(font: BitmapFont) -> Self {
        Self { font }
    }

    /// Create a text renderer with the default 8x8 font
    pub fn default_font() -> Self {
        Self::new(BitmapFont::default_8x8())
    }

    /// Draw text at the given position
    pub fn draw(&self, canvas: &mut Canvas, x: i32, y: i32, text: &str, color: Color) {
        let mut cx = x;
        let mut cy = y;

        for c in text.chars() {
            if c == '\n' {
                cx = x;
                cy += self.font.char_height as i32;
            } else if c == '\r' {
                cx = x;
            } else if c == '\t' {
                cx += (self.font.char_width * 4) as i32;
            } else {
                self.font.draw_char(canvas, cx, cy, c, color);
                cx += self.font.char_width as i32;
            }
        }
    }

    /// Draw text with a shadow effect
    pub fn draw_shadowed(
        &self,
        canvas: &mut Canvas,
        x: i32,
        y: i32,
        text: &str,
        color: Color,
        shadow_color: Color,
        offset: i32,
    ) {
        self.draw(canvas, x + offset, y + offset, text, shadow_color);
        self.draw(canvas, x, y, text, color);
    }

    /// Draw text with an outline
    pub fn draw_outlined(
        &self,
        canvas: &mut Canvas,
        x: i32,
        y: i32,
        text: &str,
        color: Color,
        outline_color: Color,
    ) {
        // Draw outline in all 8 directions
        for dy in -1..=1 {
            for dx in -1..=1 {
                if dx != 0 || dy != 0 {
                    self.draw(canvas, x + dx, y + dy, text, outline_color);
                }
            }
        }
        // Draw main text
        self.draw(canvas, x, y, text, color);
    }

    /// Draw text centered at a position
    pub fn draw_centered(&self, canvas: &mut Canvas, x: i32, y: i32, text: &str, color: Color) {
        let width = self.font.measure_string(text) as i32;
        let height = self.font.char_height as i32;
        self.draw(canvas, x - width / 2, y - height / 2, text, color);
    }

    /// Draw text right-aligned
    pub fn draw_right(&self, canvas: &mut Canvas, x: i32, y: i32, text: &str, color: Color) {
        let width = self.font.measure_string(text) as i32;
        self.draw(canvas, x - width, y, text, color);
    }

    /// Measure text dimensions
    pub fn measure(&self, text: &str) -> (u32, u32) {
        let width = self.font.measure_string(text);
        let height = self.font.measure_string_height(text);
        (width, height)
    }

    /// Get font metrics
    pub fn char_size(&self) -> (u32, u32) {
        (self.font.char_width, self.font.char_height)
    }
}

impl Default for TextRenderer {
    fn default() -> Self {
        Self::default_font()
    }
}

