BOX = (2, ['#####', '#...#', '#...#', '#...#', '#...#', '#...#', '#####'])

MARKS: Dict[str, List[str]] = {
    'acute': ['...#.', '..#..'],
    'grave': ['.#...', '..#..'],
    'circumflex': ['..#..', '.#.#.'],
    'tilde': ['.##.#', '#.##.'],
    'diaeresis': ['.#.#.', '.....'],
    'ring': ['.###.', '.#.#.'],
}
CEDILLA = '..##.'

# Latin-1 letter -> (base letter, mark); an i loses its dot under a mark
def _composed() -> Dict[str, Tuple[str, str]]:
    out: Dict[str, Tuple[str, str]] = {}
    names = {'grave': 'GRAVE', 'acute': 'ACUTE', 'circumflex': 'CIRCUMFLEX', 'tilde': 'TILDE',
             'diaeresis': 'DIAERESIS', 'ring': 'RING ABOVE'}
    for mark, letters in (('grave', 'AEIOUaeiou'), ('acute', 'AEIOUYaeiouy'), ('circumflex', 'AEIOUaeiou'),
                          ('tilde', 'ANOano'), ('diaeresis', 'AEIOUaeiouy'), ('ring', 'Aa')):
        for letter in letters:
            case = 'CAPITAL' if letter.isupper() else 'SMALL'
            try:
                char = unicodedata.lookup(f'LATIN {case} LETTER {letter.upper()} WITH {names[mark]}')
            except KeyError:
                continue
            out[char] = (letter, mark)
    return out


COMPOSED = _composed()


def rows_of(char: str) -> List[str]:
    """The character's cell: CELL_H rows of CELL_W `#`/`.` (the sixth column is the space between letters)."""
    cell = ['.' * CELL_W for _ in range(CELL_H)]

    def put(top: int, rows: List[str]) -> None:
        for i, row in enumerate(rows):
            if 0 <= top + i < CELL_H:
                cell[top + i] = row.ljust(CELL_W, '.')[:CELL_W]

    if char in ('ç', 'Ç'):
        top, rows = GLYPHS['c' if char == 'ç' else 'C']
        put(top, rows)
        put(CELL_H - 1, [CEDILLA])
        return cell
    if char in COMPOSED:
        base, mark = COMPOSED[char]
        top, rows = GLYPHS['ı' if base == 'i' else base]
        put(top, rows)
        put(top - 2, MARKS[mark])
        return cell
    top, rows = GLYPHS.get(char, BOX)
    put(top, rows)
    return cell


def cell_index(codepoint: int) -> Optional[int]:
    """Where a character is in the sheet, or None for one the font does not have (the daemon shows a box)."""
    if codepoint in ASCII:
        return codepoint - ASCII.start
    if codepoint in LATIN1:
        return len(ASCII) + codepoint - LATIN1.start
    return None


def render() -> Tuple[int, int, List[bytes]]:
    """The sheet as (width, height, RGBA rows): white where a glyph is, transparent elsewhere."""
    rows_of_cells = -(-COUNT // COLUMNS)
    width, height = COLUMNS * CELL_W, rows_of_cells * CELL_H
    pixels = [bytearray(width * 4) for _ in range(height)]
    for index, codepoint in enumerate(list(ASCII) + list(LATIN1)):
        cx, cy = (index % COLUMNS) * CELL_W, (index // COLUMNS) * CELL_H
        for dy, row in enumerate(rows_of(chr(codepoint))):
            for dx, bit in enumerate(row):
                if bit == '#':
                    pixels[cy + dy][(cx + dx) * 4:(cx + dx) * 4 + 4] = b'\xff\xff\xff\xff'
    return width, height, [bytes(r) for r in pixels]


def show(text: str) -> str:
    """The text as the screen draws it, in `#` and `.`: for a test or a look."""
    cells = [rows_of(ch) for ch in text]
    return '\n'.join(''.join(cell[y] for cell in cells) for y in range(CELL_H))
